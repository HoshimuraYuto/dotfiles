#!/usr/bin/env bash
set -euo pipefail

dry=false
# --auto [profile...]: the run hermes/watch.sh makes when profiles appear (see
# install_agent); with names, only those profiles are configured
auto=false
only=()
case ${1-} in
  -n | --dry-run) dry=true ;;
  --auto)
    auto=true
    only=("${@:2}")
    ;;
  "") ;;
  *)
    echo "Usage: $0 [-n|--dry-run]" >&2
    exit 2
    ;;
esac
failed=0
# One writing run at a time: the launchd agent may fire while this script runs by
# hand. TMPDIR differs between launchd and a shell, so the lock lives under $HOME.
if ! $dry; then
  lock=$HOME/.local/state/dotfiles/hermes-install.lock
  mkdir -p "$(dirname "$lock")"
  while ! mkdir "$lock" 2> /dev/null; do
    # A run that was killed leaves its lock behind
    if ! kill -0 "$(cat "$lock/pid" 2> /dev/null)" 2> /dev/null; then
      rm -rf "$lock"
      continue
    fi
    # The automatic run waits its turn, or the profile that triggered it is missed
    if ! $auto; then
      echo "BUSY       another hermes/install.sh is running"
      exit 1
    fi
    sleep 1
  done
  echo $$ > "$lock/pid"
  trap 'rm -rf "$lock"' EXIT
fi
repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)

# Settings and skills hold personal data, so they live in a private repository;
# this public one keeps only the installer.
private=${DOTFILES_PRIVATE:-$HOME/dotfiles-private}
profiles=$private/hermes/profiles
if [[ ! -d $profiles ]]; then
  echo "MISSING    $profiles (clone the private repository first)"
  exit 1
fi

# Hermes has no global instructions file; SOUL.md is the persona. The shared rules
# become a generated skill outside both repositories, which the shared config.txt
# adds to skills.external_dirs and skills.auto_load.
install_rules() {
  local to=$HOME/.local/share/dotfiles/hermes/skills/dotfiles-rules/SKILL.md
  local marker='# Generated by dotfiles/hermes/install.sh; edit the source rules instead.'
  local content file third=
  content=$(
    printf -- '---\nname: dotfiles-rules\n%s\n' "$marker"
    printf 'description: "Always-on working rules shared with Claude and Codex."\n---\n\n'
    for file in "$repo"/rules/*.md "$private/hermes/instructions.md"; do
      [[ -f $file ]] || continue
      cat "$file"
      printf '\n'
    done
  )
  if [[ -L $to || (-e $to && ! -f $to) ]]; then
    echo "CONFLICT   $to is not a regular file"
    failed=1
    return
  fi
  if [[ -s $to ]]; then
    third=$(sed -n 3p "$to")
    if [[ $third != "$marker" ]]; then
      echo "CONFLICT   $to has unmanaged instructions"
      failed=1
      return
    fi
    if [[ $(cat "$to") == "$content" ]]; then
      echo "ok         $to"
      return
    fi
  fi
  if $dry; then
    echo "would write $to"
    return
  fi
  mkdir -p "$(dirname "$to")"
  printf '%s\n' "$content" > "$to"
  echo "generated  $to"
}
install_rules

# The private repository has its own git hooks (gitleaks, prettier, commitlint)
if [[ -f $private/package.json ]] && ! $auto; then
  if $dry; then
    echo "would run  npm install in $private"
  else
    (cd "$private" && mise exec -- npm install)
  fi
fi

# hermes reads stdin, so every call gets /dev/null to keep the loops' input intact
h() {
  hermes -p "$profile" "$@" < /dev/null
}

# Values in config.txt are JSON; a string starting with ~/ is relative to $HOME
# and {profile} stands for the profile's name
want_json() {
  jq -c --arg home "$HOME" --arg profile "$profile" \
    'walk(if type == "string" then sub("^~/"; $home + "/") | gsub("\\{profile\\}"; $profile) else . end)' <<< "$1"
}

check_skills() {
  local md skill copy
  [[ -d $dir/skills ]] || return 0
  while IFS= read -r md; do
    skill=$(basename "$(dirname "$md")")
    copy=$(find "$home/skills" -path "$home/skills/.*" -prune -o -path "*/$skill/SKILL.md" -print -quit 2> /dev/null || true)
    if [[ -n $copy ]]; then
      echo "CONFLICT   $profile: ${copy%/SKILL.md} shadows the repo skill"
      failed=1
    fi
  done < <(find "$dir/skills" -name SKILL.md)
}

# Machine -> repo: skills in the profile's own skills/ that the repo does not hold.
# Unmodified bundled skills belong to Hermes; anything else (new or edited) should
# move into the repo, where create_dir and external_dirs keep later changes.
check_local() {
  local md skill
  while IFS= read -r md; do
    skill=$(basename "$(dirname "$md")")
    # A copy of a repo skill is already reported by check_skills
    [[ -n $(find "$dir/skills" -path "*/$skill/SKILL.md" -print -quit 2> /dev/null || true) ]] && continue
    grep -qsx "$skill:.*" "$home/skills/.bundled_manifest" && continue
    echo "UNMANAGED  $profile: ${md%/SKILL.md}"
    failed=1
  done < <(find "$home/skills" -path "$home/skills/.*" -prune -o -name SKILL.md -print 2> /dev/null || true)
  while read -r skill; do
    [[ -n $(find "$dir/skills" -path "*/$skill/SKILL.md" -print -quit 2> /dev/null || true) ]] && continue
    echo "UNMANAGED  $profile: $skill (edited bundled skill)"
    failed=1
  done < <(h skills list-modified 2> /dev/null | sed -n 's/^ *~ //p')
}

install_plugins() {
  local plugin extra
  [[ -f $dir/plugins.txt ]] || return 0
  while read -r plugin extra; do
    [[ -z $plugin || $plugin == \#* ]] && continue
    if grep -qsF "\"catalog_name\": \"$plugin\"" "$home"/plugins/*/.hermes-catalog.json; then
      echo "ok         $profile: plugin $plugin"
    elif $dry; then
      echo "would add  $profile: plugin $plugin"
    elif h plugins install "$plugin" --enable --yes-deps > /dev/null; then
      echo "added      $profile: plugin $plugin"
    else
      echo "FAILED     $profile: plugin $plugin"
      failed=1
    fi
  done < "$dir/plugins.txt"
}

# Settings for every profile come from the shared config.txt; the profile's own
# config.txt overrides a key it repeats. Hermes has no setting that applies to all
# profiles, so this is how a profile created later (e.g. a bot) gets them too.
config_lines() {
  local files=()
  for f in "$private/hermes/config.txt" "$dir/config.txt"; do
    [[ -f $f ]] && files+=("$f")
  done
  ((${#files[@]})) || return 0
  awk '$1 == "" || $1 ~ /^#/ { next }
    !($1 in line) { order[++n] = $1 }
    { line[$1] = $0 }
    END { for (i = 1; i <= n; i++) print line[order[i]] }' "${files[@]}"
}

# A problem that leaves a profile without its always-on skills; the automatic run
# raises a notification each time until the profile is fixed or skipped.
alert() {
  echo "$1"
  failed=1
  if $auto; then
    osascript -e "display notification \"$1\" with title \"dotfiles: Hermes\"" > /dev/null 2>&1 || true
  fi
}

# Every skill the merged config.txt lists in skills.auto_load must be in the profile's
# setting and in one of its skill directories, or Hermes skips it without an error.
verify_auto_load() {
  local line want have name dirs found
  line=$(config_lines | awk '$1 == "skills.auto_load"')
  [[ -n $line ]] || return 0
  want=$(want_json "${line#* }")
  have=$(h config get --json skills.auto_load 2> /dev/null | jq -c . 2> /dev/null || echo '[]')
  dirs=$(
    echo "$home/skills"
    h config get --json skills.create_dir 2> /dev/null | jq -r 'strings' 2> /dev/null || true
    h config get --json skills.external_dirs 2> /dev/null | jq -r '.[]?' 2> /dev/null || true
  )
  while read -r name; do
    if ! jq -e --arg n "$name" 'index($n)' <<< "$have" > /dev/null; then
      alert "NOT LOADED $profile: $name is not in skills.auto_load"
      continue
    fi
    found=
    while read -r d; do
      [[ -n $d && -d $d ]] || continue
      found=$(find "$d" -path "*/$name/SKILL.md" -print -quit 2> /dev/null || true)
      [[ -n $found ]] && break
    done <<< "$dirs"
    [[ -n $found ]] || alert "NOT LOADED $profile: $name is in no skill directory"
  done < <(jq -r '.[]' <<< "$want")
}

apply_config() {
  local key value want have
  while read -r key value; do
    [[ -z $key || $key == \#* ]] && continue
    if ! want=$(want_json "$value" 2> /dev/null) || [[ -z $want ]]; then
      echo "INVALID    $profile: $key $value"
      failed=1
      continue
    fi
    have=$(h config get --json "$key" 2> /dev/null | jq -c . 2> /dev/null || true)
    if [[ $have == "$want" ]]; then
      echo "ok         $profile: $key"
    elif $dry; then
      echo "would set  $profile: $key"
    elif h config set "$key" "$(jq -r 'if type == "string" then . else tojson end' <<< "$want")" > /dev/null; then
      echo "set        $profile: $key"
    else
      alert "FAILED     $profile: $key"
    fi
  done < <(config_lines)
}

# A profile's home is <root>/profiles/<name>, where <root> is the default profile's home
hermes_root() {
  local path
  path=$(profile=default h config path 2> /dev/null) && dirname "$path"
}

# Profiles in the repository, then any other Hermes profile on this machine (one
# created from the Bots tab, say), which gets the shared settings only.
# Profiles named in the private repository's hermes/skip-profiles.txt are left alone.
profile_names() {
  local root skip=$private/hermes/skip-profiles.txt
  [[ -f $skip ]] || skip=/dev/null
  {
    if ((${#only[@]})); then
      printf '%s\n' "${only[@]}"
    else
      for dir in "$profiles"/*/; do
        [[ -d $dir ]] && basename "$dir"
      done
      echo default
      if root=$(hermes_root); then
        for dir in "$root"/profiles/*/; do
          [[ -d $dir ]] && basename "$dir"
        done
      fi
    fi
  } | awk -v list="$skip" 'BEGIN {
      while ((getline line < list) > 0) {
        split(line, f, " ")
        if (f[1] != "" && f[1] !~ /^#/) skip[f[1]] = 1
      }
    }
    !($0 in skip) && !seen[$0]++'
}

# Hermes has no hook for a new profile, so a launch agent keeps hermes/watch.sh
# running, which re-runs this script with --auto when <root>/profiles changes.
# launchd's own WatchPaths missed new directories in testing, so it is not used.
install_agent() {
  local label=dotfiles.hermes-sync
  local to=$HOME/Library/LaunchAgents/$label.plist
  local root path_dirs content
  root=$(hermes_root) || return 0
  if ! command -v fswatch > /dev/null; then
    echo "MISSING    fswatch (brew install fswatch), needed to configure new profiles"
    failed=1
    return
  fi
  path_dirs=$(for c in hermes jq mise osascript fswatch; do
    command -v "$c" > /dev/null && dirname "$(command -v "$c")"
  done | awk '!seen[$0]++' | paste -sd: -)
  # Quoted replacements are literal, even where bash treats & in them as the match
  content=$(< "$repo/hermes/$label.plist")
  content=${content//@REPO@/"$repo"}
  content=${content//@ROOT@/"$root"}
  content=${content//@HOME@/"$HOME"}
  content=${content//@PATH@/"$path_dirs:/usr/bin:/bin:/usr/sbin:/sbin"}
  content=${content//@PRIVATE@/"$private"}
  if [[ -f $to && $(cat "$to") == "$content" ]]; then
    if launchctl print "gui/$(id -u)/$label" > /dev/null 2>&1; then
      echo "ok         $to"
    elif $dry; then
      echo "would load $label"
    else
      launchctl bootstrap "gui/$(id -u)" "$to" && echo "loaded     $label"
    fi
    return
  fi
  if [[ -e $to ]] && ! grep -q 'Generated by dotfiles/hermes/install.sh' "$to"; then
    echo "CONFLICT   $to is not generated by this script"
    failed=1
    return
  fi
  if $dry; then
    echo "would write $to"
    return
  fi
  mkdir -p "$(dirname "$to")" "$HOME/Library/Logs"
  printf '%s\n' "$content" > "$to"
  launchctl bootout "gui/$(id -u)/$label" > /dev/null 2>&1 || true
  launchctl bootstrap "gui/$(id -u)" "$to"
  echo "generated  $to"
}

while read -r profile; do
  dir=$profiles/$profile
  if ! h config path > /dev/null 2>&1; then
    # Creating a profile is left to a run by hand
    if $dry || $auto; then
      echo "would add  profile $profile"
      continue
    fi
    if ! hermes profile create "$profile" --no-skills < /dev/null > /dev/null; then
      echo "FAILED     profile $profile"
      failed=1
      continue
    fi
    echo "added      profile $profile"
  fi
  home=$(dirname "$(h config path)")
  # Reports for a person, which the automatic run has no one to show to
  if ! $auto; then
    check_skills
    check_local
  fi
  # Plugins first: a plugin can provide the model.provider that config.txt selects
  install_plugins
  apply_config
  verify_auto_load
done < <(profile_names)
$auto || install_agent
exit "$failed"
