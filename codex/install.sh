#!/usr/bin/env bash
set -euo pipefail

src=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo=$(cd "$src/.." && pwd)
dest=${DOTFILES_CODEX_DIR:-${CODEX_HOME:-$HOME/.codex}}
skills_dest=${DOTFILES_SKILLS_DIR:-$HOME/.agents/skills}
dry=false
case ${1-} in
  -n | --dry-run) dry=true ;;
  "") ;;
  *)
    echo "Usage: $0 [-n|--dry-run]" >&2
    exit 2
    ;;
esac
source "$repo/scripts/install-agent.sh"

install_instructions() {
  local to=$dest/AGENTS.md
  local marker='<!-- Generated by dotfiles/codex/install.sh; edit the source rules instead. -->'
  local first content file
  content=$(
    printf '%s\n\n' "$marker"
    for file in "$repo"/rules/*.md "$src/instructions.md"; do
      cat "$file"
      printf '\n'
    done
  )
  if [[ -L $to || (-e $to && ! -f $to) ]]; then
    echo "CONFLICT   $to is not a regular file"
    failed=1
    return
  fi
  if [[ -s $to ]]; then
    IFS= read -r first < "$to" || true
    if [[ $first != "$marker" ]]; then
      echo "CONFLICT   $to has unmanaged instructions"
      failed=1
      return
    fi
    if [[ $(cat "$to") == "$content" ]]; then
      echo "ok         $to"
      return
    fi
  fi
  if $dry; then
    echo "would write $to"
    return
  fi
  mkdir -p "$dest"
  printf '%s\n' "$content" > "$to"
  echo "generated  $to"
}

install_instructions
link "$src/dotfiles.config.toml" "$dest/dotfiles.config.toml"
link "$src/rules/dotfiles.rules" "$dest/rules/dotfiles.rules"
install_skills codex "$src/skills" "$HOME/.agents/skills"

for override in "$src"/skill-overrides/*/; do
  name=$(basename "$override")
  if [[ -f $skills_dest/$name/SKILL.md ]] || $dry; then
    link "${override%/}/agents/openai.yaml" "$skills_dest/$name/agents/openai.yaml"
  else
    echo "FAILED     cannot apply policy to missing skill $name"
    failed=1
  fi
done
exit "$failed"
