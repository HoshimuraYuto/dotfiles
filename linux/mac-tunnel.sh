#!/usr/bin/env bash
# Run on the Mac. Makes localhost:<local port> reach the Linux machine's RDP port
# through ssh, started by launchd only while a client is connected.
set -euo pipefail

src=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
dry=false
remove=false
args=()
for a in "$@"; do
  case $a in
    -n | --dry-run) dry=true ;;
    --remove) remove=true ;;
    *) args+=("$a") ;;
  esac
done
if ((${#args[@]} < 1 || ${#args[@]} > 3)) || { ! $remove && ((${#args[@]} < 2)); }; then
  cat >&2 << EOF
Usage: $0 [-n] <ssh host> <rdp port> [local port, default 3389]
       $0 --remove <ssh host>
<ssh host> is the Host entry in ~/.ssh/config that install.sh printed.
EOF
  exit 2
fi
host=${args[0]}
port=${args[1]-}
local_port=${args[2]:-3389}
label=dotfiles.rdp-tunnel.$host
plist=$HOME/Library/LaunchAgents/$label.plist
domain=gui/$(id -u)

if $remove; then
  if $dry; then
    echo "would remove $plist"
    exit 0
  fi
  launchctl bootout "$domain/$label" 2> /dev/null || true
  rm -f "$plist"
  echo "removed    $label"
  exit 0
fi

for p in "$port" "$local_port"; do
  if ! [[ $p =~ ^[0-9]+$ ]] || ((p < 1 || p > 65535)); then
    echo "INVALID    port $p" >&2
    exit 2
  fi
done

# DOTFILES_SSH_CONFIG points ssh at another config file; the test uses it
ssh_config=${DOTFILES_SSH_CONFIG-}
ssh_f=()
config_arg=
if [[ -n $ssh_config ]]; then
  ssh_f=(-F "$ssh_config")
  config_arg="<string>-F</string><string>$ssh_config</string>"
fi

# The job runs ssh without a terminal: the host must resolve and log in with a key
if ! ssh "${ssh_f[@]}" -G "$host" > /dev/null 2>&1; then
  echo "INVALID    ssh cannot read the config for $host" >&2
  exit 2
fi

content=$(< "$src/mac-tunnel.plist")
content=${content//@LABEL@/"$label"}
content=${content//@HOST@/"$host"}
content=${content//@PORT@/"$port"}
content=${content//@LOCAL_PORT@/"$local_port"}
content=${content//@HOME@/"$HOME"}
content=${content//@SSH_CONFIG@/"$config_arg"}

if [[ -f $plist && $(< "$plist") == "$content" ]] \
  && launchctl print "$domain/$label" > /dev/null 2>&1; then
  echo "ok         $label"
  exit 0
fi
if [[ -f $plist ]] && ! grep -qF 'Generated by dotfiles/linux/mac-tunnel.sh' "$plist"; then
  echo "CONFLICT   $plist exists and is not managed by dotfiles"
  exit 1
fi
# Another program may already hold the port (an older job of this script is replaced below)
if lsof -nP -iTCP:"$local_port" -sTCP:LISTEN > /dev/null 2>&1 \
  && ! launchctl print "$domain/$label" > /dev/null 2>&1; then
  echo "CONFLICT   localhost:$local_port is in use; pass another local port" >&2
  exit 1
fi
if $dry; then
  echo "would write $plist and load $label"
  exit 0
fi

mkdir -p "$(dirname "$plist")"
printf '%s\n' "$content" > "$plist"
plutil -lint -s "$plist"
launchctl bootout "$domain/$label" 2> /dev/null || true
launchctl bootstrap "$domain" "$plist"
echo "loaded     $label: localhost:$local_port -> $host -> localhost:$port"

# Prove the path end to end: launchd accepts, ssh logs in, the RDP server answers
err=$(ssh "${ssh_f[@]}" -o BatchMode=yes -o ConnectTimeout=5 "$host" true 2>&1 > /dev/null) && ok=true || ok=false
if $ok && ! grep -q 'IDENTIFICATION HAS CHANGED' <<< "$err"; then
  echo "ok         ssh $host logs in without a prompt"
elif grep -q 'IDENTIFICATION HAS CHANGED' <<< "$err"; then
  # ssh still runs commands then, but refuses -W, so the tunnel would fail silently
  cat >&2 << EOF
FAILED     $host's host key changed (reinstalled?); ssh refuses to forward.
           If you expected that: ssh-keygen -R '[<address>]:<port>', then ssh $host once.
EOF
  exit 1
elif grep -q 'Host key verification failed' <<< "$err"; then
  echo "FAILED     $host's host key is not known yet; run ssh $host once and accept it" >&2
  exit 1
else
  echo "FAILED     ssh $host needs a prompt; the tunnel cannot log in" >&2
  exit 1
fi
if nc -z -G 5 127.0.0.1 "$local_port"; then
  echo "ok         localhost:$local_port accepts connections"
fi
if [[ $local_port == 3389 ]]; then
  echo "Connect Windows App to: localhost"
else
  echo "Connect Windows App to: localhost:$local_port"
fi
